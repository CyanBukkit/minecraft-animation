import assert from 'node:assert/strict';
import { copyFile, mkdir, mkdtemp, readFile, stat, writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const npm = process.env.npm_execpath;
assert.ok(npm, '请通过 npm run test:package 运行');
const execute = (file, args, cwd) => execFileSync(process.execPath, [file, ...args], {
  cwd, encoding: 'utf8', windowsHide: true, timeout: 180000, stdio: ['ignore', 'pipe', 'pipe'],
});
const npmRun = (args, cwd = root) => execute(npm, args, cwd);
const readJson = async file => JSON.parse(await readFile(file, 'utf8'));
const pkg = await readJson(path.join(root, 'package.json'));
const release = path.join(root, 'artifacts/release');
const work = path.join(root, 'artifacts/package-verification');
await mkdir(release, { recursive: true });
await mkdir(work, { recursive: true });
const directory = await mkdtemp(path.join(work, 'run-'));
const [pack] = JSON.parse(npmRun(['pack', '--ignore-scripts', '--json', '--pack-destination', directory]));
const names = pack.files.map(file => file.path);
for (const required of ['README.md', 'bin/minecraft-animation.js', 'dist/index.html', 'docs/LICENSE.md', 'docs/downloads/minecraft-animation.skill', 'docs/skills/minecraft-animation/SKILL.md']) assert.ok(names.includes(required), required);
const forbidden = names.filter(name => /(^|\/)(uploads|skins|node_modules|\.git|\.github)(\/|$)|\.mca$|\.jar$|\.blend$|(^|\/)\.env|task-mca|cleanup-001/.test(name));
assert.deepEqual(forbidden, []);
const archive = path.join(directory, pack.filename);
const install = path.join(directory, 'installed');
await mkdir(install);
await writeFile(path.join(install, 'package.json'), JSON.stringify({ private: true }) + '\n');
npmRun(['install', archive, '--ignore-scripts', '--no-audit', '--no-fund'], install);
const installedRoot = path.join(install, 'node_modules/minecraft-animation');
const cli = path.join(installedRoot, 'bin/minecraft-animation.js');
const run = (...args) => execute(cli, args, install);
assert.equal(run('--version').trim(), pkg.version);
assert.equal(run('skill'), await readFile(path.join(root, 'docs/skills/minecraft-animation/SKILL.md'), 'utf8') + '\n');
assert.deepEqual(await readFile(path.join(installedRoot, 'docs/downloads/minecraft-animation.skill')), await readFile(path.join(root, 'docs/downloads/minecraft-animation.skill')));
run('create', 'mcbreak', '--prompt', '人物挖掘树');
assert.equal((await readJson(path.join(install, 'mcbreak/docs/brief.json'))).prompt, '人物挖掘树');
const source = path.join(install, 'mcbreak/scene.mjs');
const original = await readFile(source, 'utf8');
assert.throws(() => run('create', 'mcbreak'), error => error.status === 1);
assert.equal(await readFile(source, 'utf8'), original);
// Execute the README's real code example, not a separate approximation.
const readme = await readFile(path.join(root, 'README.md'), 'utf8');
const match = readme.match(/~~~js\n([\s\S]*?)\n~~~/);
assert.ok(match, 'README 应包含可运行的 scene.mjs 示例');
await writeFile(source, match[1] + '\n');
run('build', 'mcbreak');
const project = await readJson(path.join(install, 'mcbreak/project.json'));
assert.equal(project.name, '林间挖树');
assert.equal(project.cameraTracks.fov.at(-1).value, 36);
const safe = JSON.parse(run('check', 'mcbreak'));
assert.equal(safe.passed, true); assert.equal(safe.collisionCount, 0);
assert.equal(JSON.parse(run('check', 'mcbreak/project.json')).passed, true);
const unsafe = structuredClone(project);
unsafe.actors[0].tracks['rightArm.z'] = [{ time: 0, value: -0.7, easing: 'linear' }];
await writeFile(path.join(install, 'unsafe.json'), JSON.stringify(unsafe) + '\n');
assert.throws(() => run('check', 'unsafe.json'), error => error.status === 2 && JSON.parse(error.stdout).collisionCount > 0);
assert.throws(() => run('render', 'unsafe.json', '--output', 'rejected'), error => error.status === 1 && error.stderr.includes('碰撞验收未通过'));
await assert.rejects(stat(path.join(install, 'rejected')), { code: 'ENOENT' });
// A consumer install may resolve newer Playwright than the source lockfile.
execute(path.join(install, 'node_modules/playwright/cli.js'), ['install', 'chromium'], install);
run('render', 'mcbreak', '--output', 'rendered', '--width', '320', '--height', '180');
const receipt = await readJson(path.join(install, 'rendered/receipt.json'));
assert.equal(receipt.frameCount, 96); assert.equal(receipt.fps, 24);
assert.equal(receipt.width, 320); assert.equal(receipt.height, 180);
assert.equal(receipt.duration, 4); assert.equal(receipt.decoded.lastFrameDecoded, true);
assert.equal(receipt.bytes, (await stat(path.join(install, 'rendered/movie.webm'))).size);
const report = { passed: true, name: pkg.name, version: pkg.version, files: names.length, checkedSamples: safe.checkedSamples, receipt };
await copyFile(archive, path.join(release, pack.filename));
await writeFile(path.join(release, 'verification.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
